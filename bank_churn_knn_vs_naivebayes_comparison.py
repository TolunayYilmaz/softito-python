print(f'📊 Doğruluk (Acc)  : {nb_acc:.4f}  ({nb_acc*100:.2f}%)')
print(f'📊 AUC-ROC         : {nb_auc:.4f}')
print(f'📊 F1 Skoru        : {nb_f1:.4f}')
print(f'📊 Precision       : {nb_prec:.4f}')
print(f'📊 Recall          : {nb_recall:.4f}')
print()
print('📋 Detaylı Rapor:')
# Hedef isimleri Churn verisine göre güncellendi
print(classification_report(y_test, nb_pred, target_names=['Kaldı (0)', 'Ayrıldı (1)']))

# ─── Banka Churn için Naive Bayes'in Öğrendiği Dağılımları Görselleştir ────
# GaussianNB sürekli verilere çan eğrisi uydurur. Kategorik (0/1) sütunlarda
# anlamsız grafikler çıkmaması için veri setindeki 4 sürekli özelliği seçiyoruz.

fig, axes = plt.subplots(2, 2, figsize=(14, 10))
axes = axes.ravel()

colors = ['#3498db', '#e74c3c']  # 0: Kaldı (Mavi), 1: Ayrıldı (Kırmızı)
class_labels = ['Kaldı (0)', 'Ayrıldı (1)']

# Görselleştirmek istediğimiz sürekli (continuous) özellikler
features_to_plot = ['CreditScore', 'Age', 'Balance', 'EstimatedSalary']

# Bu özelliklerin X.columns içindeki indekslerini bul (theta_ ve var_ matrisleri için)
feature_indices = [X.columns.get_loc(feat) for feat in features_to_plot]

for i, (feat, feat_idx) in enumerate(zip(features_to_plot, feature_indices)):
    for c in range(2):    # Her sınıf için (0=Kaldı, 1=Ayrıldı)
        mu    = nb_model.theta_[c, feat_idx]
        # theta_[c, i]: c. sınıfın i. özellik için öğrenilen ortalaması (μ)

        sigma = np.sqrt(nb_model.var_[c, feat_idx])
        # var_[c, i]: c. sınıfın i. özellik için öğrenilen varyansı (σ²)

        x_range = np.linspace(mu - 4*sigma, mu + 4*sigma, 200)
        # μ ± 4σ aralığı: Normal dağılımın %99.99'unu kapsar

        pdf = (1 / (sigma * np.sqrt(2*np.pi))) * np.exp(-0.5 * ((x_range - mu) / sigma)**2)
        # Gaussian PDF formülü

        axes[i].plot(x_range, pdf, color=colors[c], linewidth=2.5, label=class_labels[c])
        axes[i].fill_between(x_range, pdf, alpha=0.15, color=colors[c])  # Alan gölgesi
        axes[i].axvline(mu, color=colors[c], linestyle='--', alpha=0.6, linewidth=1.5)
        # Dikey kesik çizgi: ortalama μ'yü işaret eder

    axes[i].set_title(f'Özellik: {feat}', fontsize=12, fontweight='bold')
    axes[i].set_xlabel('Değer')
    axes[i].set_ylabel('Olasılık Yoğunluğu')
    axes[i].legend(fontsize=10)

plt.suptitle('🟠 Naive Bayes — Öğrenilen Gaussian Dağılımlar',
             fontsize=15, fontweight='bold')
