# Sklearn Pipeline (Sadece ölçekleme yapan normal modeller için)
from sklearn.pipeline import Pipeline as SklearnPipeline

# Imblearn Pipeline (İçinde SMOTE barındıran modeller için - Veri sızıntısını önler!)
from imblearn.pipeline import Pipeline as ImblearnPipeline
print('🔄 3 Model İçin 5-Fold Cross Validation (Metrik: F1-Score)...')
print('='*65)

# ─── 1. Modellerin ve Pipeline'ların Hazırlanması ──────────────────────────

# Model 1: Orijinal KNN (Ölçekleme + KNN)
knn_pipe = SklearnPipeline([
    ('scaler', StandardScaler()),
    ('knn', KNeighborsClassifier(n_neighbors=19, metric='euclidean'))
])

# Model 2: Naive Bayes (Ölçekleme gerekmez)
nb_model = GaussianNB()

# Model 3: SMOTE KNN (Ölçekleme + SMOTE + KNN)
# DİKKAT: SMOTE'un sadece eğitim katmanlarında çalışması için ImblearnPipeline ŞARTTIR.
smote_knn_pipe = ImblearnPipeline([
    ('scaler', StandardScaler()),
    ('smote', SMOTE(random_state=42)),
    ('knn', KNeighborsClassifier(n_neighbors=19, metric='euclidean'))
])

# ─── 2. Çapraz Doğrulama (CV) Hesaplamaları ────────────────────────────────
# Bankacılık verisi için accuracy yerine F1-Score'u baz alıyoruz
metric = 'f1'

knn_cv       = cross_val_score(knn_pipe, X, y, cv=5, scoring=metric)
nb_cv        = cross_val_score(nb_model, X, y, cv=5, scoring=metric)
smote_knn_cv = cross_val_score(smote_knn_pipe, X, y, cv=5, scoring=metric)

print(f'🔵 KNN (Orijinal)  CV: {knn_cv.round(4)} → Ort: {knn_cv.mean():.4f} ± {knn_cv.std():.4f}')
print(f'🟠 Naive Bayes     CV: {nb_cv.round(4)} → Ort: {nb_cv.mean():.4f} ± {nb_cv.std():.4f}')
print(f'🟢 KNN (SMOTE)     CV: {smote_knn_cv.round(4)} → Ort: {smote_knn_cv.mean():.4f} ± {smote_knn_cv.std():.4f}')

# ─── 3. CV Görselleştirme ──────────────────────────────────────────────────
fig, ax = plt.subplots(figsize=(12, 6))
x_fold = np.arange(5)

# Çizgiler
ax.plot(x_fold, knn_cv, 'b-o', markersize=8, linewidth=2, label=f'KNN Orijinal (Ort={knn_cv.mean():.4f})')
