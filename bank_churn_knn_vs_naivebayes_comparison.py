# ─── Banka Verisine Uygun Eğitim Boyutları ─────────────────────────────────
# Eğitim verimiz toplam 8000 satır. Modelleri yavaş yavaş artan verilerle eğiteceğiz.
sizes = [500, 1000, 2000, 4000, 6000, 8000]

knn_train_times, nb_train_times = [], []
knn_pred_times,  nb_pred_times  = [], []

for s in sizes:
    Xs    = X_train_scaled[:s]   # KNN için ölçeklenmiş eğitim verisi
    Xs_nb = X_train.iloc[:s]     # NB için ham eğitim verisi
    ys    = y_train.iloc[:s]     # İlgili etiketler

    # ── KNN Eğitim Süresi ──
    m_knn = KNeighborsClassifier(n_neighbors=19) # Bulduğumuz en iyi K
    t = time.time()
    m_knn.fit(Xs, ys)            # Veriyi belleğe al (Lazy Learning)
    knn_train_times.append(time.time() - t)

    # ── KNN Tahmin Süresi ──
    t = time.time()
    m_knn.predict(X_test_scaled) # 2000 test örneğinin HER BİRİ için 's' tane uzaklık hesapla
    knn_pred_times.append(time.time() - t)

    # ── NB Eğitim Süresi ──
    m_nb = GaussianNB()
    t = time.time()
    m_nb.fit(Xs_nb, ys)          # Ortalama ve varyans hesapla
    nb_train_times.append(time.time() - t)

    # ── NB Tahmin Süresi ──
    t = time.time()
    m_nb.predict(X_test)         # Sadece istatistiksel formülü uygula
    nb_pred_times.append(time.time() - t)

