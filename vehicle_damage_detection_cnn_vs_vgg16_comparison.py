# ── 8. CNN Mimarisi (4 Bloklu Derin Versiyon) ─────────────────
from tensorflow.keras import models, layers

def build_cnn(input_shape=(64, 64, 3)):
    # Türkçe karakterler temizlendi (Arac_Hasar_CNN_Derin)
    model = models.Sequential(name='Arac_Hasar_CNN_Derin')

    # ── GİRİŞ ────────────────────────────────────────────────
    model.add(layers.Input(shape=input_shape))

    # ── BLOK 1: İlkel Özellikler (Kenarlar, renk geçişleri) ──
    model.add(layers.Conv2D(32, (3, 3), padding='same', activation='relu'))
    model.add(layers.BatchNormalization())
    model.add(layers.Conv2D(32, (3, 3), padding='same', activation='relu'))
    model.add(layers.BatchNormalization())
    model.add(layers.MaxPooling2D((2, 2))) # 64x64 → 32x32
    model.add(layers.Dropout(0.25))

    # ── BLOK 2: Orta Seviye Özellikler (Ufak çizikler) ───────
    model.add(layers.Conv2D(64, (3, 3), padding='same', activation='relu'))
    model.add(layers.BatchNormalization())
    model.add(layers.Conv2D(64, (3, 3), padding='same', activation='relu'))
    model.add(layers.BatchNormalization())
    model.add(layers.MaxPooling2D((2, 2))) # 32x32 → 16x16
    model.add(layers.Dropout(0.25))

    # ── BLOK 3: Yüksek Seviye Özellikler (Derin çizikler, göçükler)
    model.add(layers.Conv2D(128, (3, 3), padding='same', activation='relu'))
    model.add(layers.BatchNormalization())
    model.add(layers.Conv2D(128, (3, 3), padding='same', activation='relu'))
    model.add(layers.BatchNormalization())
    model.add(layers.MaxPooling2D((2, 2))) # 16x16 → 8x8
    model.add(layers.Dropout(0.25))

    # ── BLOK 4: Soyut Özellikler (Genel hasar formu) ─────────
    model.add(layers.Conv2D(256, (3, 3), padding='same', activation='relu'))
    model.add(layers.BatchNormalization())
    model.add(layers.MaxPooling2D((2, 2))) # 8x8 → 4x4
    model.add(layers.Dropout(0.25))

    # ── SINIFLANDIRICI BAŞ ────────────────────────────────────
    model.add(layers.GlobalAveragePooling2D())

    model.add(layers.Dense(256, activation='relu'))
    model.add(layers.BatchNormalization())
    model.add(layers.Dropout(0.50))

    model.add(layers.Dense(64, activation='relu'))
    model.add(layers.Dropout(0.30))

    model.add(layers.Dense(1, activation='sigmoid'))

    return model

# Modeli oluştur ve belleğe al
