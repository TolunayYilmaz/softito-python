import numpy as np

# 5×5 Yapay Görüntü (Sanki bir araç kapısı)
# 1 ve 2'ler: Pürüzsüz boya (karanlık/gri alanlar)
# 8 ve 9'lar: Kaportadaki dikey, parlayan derin çizik
goruntu = np.array([
    [1, 1, 9, 1, 2],
    [2, 1, 8, 2, 1],
    [1, 2, 9, 1, 1],
    [1, 1, 8, 2, 2],
    [2, 1, 9, 1, 1]
], dtype=np.float32)

# 3×3 Dikey Çizik (Çizgi) Algılama Filtresi
# Ortası yüksek pozitif (çiziği arar), yanları negatif (çiziğin etrafındaki düzlüğü arar)
filtre = np.array([
    [-1,  2, -1],
    [-1,  2, -1],
    [-1,  2, -1]
], dtype=np.float32)

# Elle evrişim — 'valid' padding (kenar ekleme yok)
H, W = goruntu.shape
k    = filtre.shape[0]
cikis = np.zeros((H - k + 1, W - k + 1))

for i in range(H - k + 1):
    for j in range(W - k + 1):
        bolge      = goruntu[i:i+k, j:j+k]   # 3×3 bölge al (kaportada gezin)
        cikis[i,j] = np.sum(bolge * filtre)  # Nokta çarpımı (Örtüşüyor mu?)

print("Giriş görüntüsü (5×5 Kaporta Parçası - Ortada çizik var):")
print(goruntu.astype(int))

