def build_transfer_model(input_shape=(64, 64, 3)):
    """
    VGG16 tabanlı transfer learning modeli.
    CPU optimizasyonu için giriş boyutu 64x64'e ayarlanmıştır.
    """
    # ── Temel Model (VGG16'nın Gövdesi) ────────────────────────
    # Eğer daha önce inmediyse yaklaşık 50MB'lık ağırlık dosyasını indirecektir.
    base = VGG16(
        weights     = 'imagenet',  # ImageNet'in devasa bilgisini kullan
        include_top = False,       # Orijinal 1000 sınıflı başı atıyoruz
        input_shape = input_shape
    )
    print(f"VGG16 katman sayısı: {len(base.layers)}")

    # Çok yer kaplamaması için mimari yazdırma kısmını şimdilik kapatabilirsin
    # veya orijinal kodundaki gibi bırakabilirsin.

    # VGG16'nın kendi bilgilerini bozmamak için önce gövdeyi "donduruyoruz"
    base.trainable = False
    print(f"\nEğitilebilir ağırlık (Sadece baş kısım): {sum(tf.size(w).numpy() for w in base.trainable_weights):,}")

    # ── Özel Sınıflandırıcı Baş (Bizim Hasar Dedektörümüz) ─────
    inputs  = keras.Input(shape=input_shape)
    x       = base(inputs, training=False)   # Gövdeden geçir
    x       = layers.GlobalAveragePooling2D()(x) # Özellikleri özetle
    x       = layers.Dense(256, activation='relu')(x)
    x       = layers.BatchNormalization()(x)
    x       = layers.Dropout(0.50)(x)

    # Çıkış: Tek nöron. < 0.5 Hasarsız, >= 0.5 Hasarlı
    outputs = layers.Dense(1, activation='sigmoid')(x)

    model = keras.Model(inputs, outputs, name='Transfer_VGG16_Hasar')
    return model, base

