def generate_synthetic_image(label: int, size: int = 64) -> np.ndarray:
    """
    label=0 → Hasarsız: Düzgün kaporta, temiz çizgiler
    label=1 → Hasarlı: Üzerinde göçük (koyu lekeler) ve çizikler (beyaz/siyah çizgiler) olan kaporta
    """
    # Açık gri/mavi asfalt benzeri arka plan
    img = Image.new('RGB', (size, size),
                    color=(random.randint(180, 200),
                           random.randint(180, 200),
                           random.randint(190, 210)))
    draw = ImageDraw.Draw(img)
    cx, cy = size // 2, size // 2   # Merkez koordinatı

    # Aracın temel rengi (rastgele)
    car_color = (random.randint(50, 200), random.randint(50, 200), random.randint(50, 200))
    w, h = size // 3, size // 6

    # ── Ortak Çizim (Araç İskeleti) ───────────────────────────
    # Alt Gövde
    draw.rectangle([cx-w, cy-h, cx+w, cy+h], fill=car_color)
    # Tavan / Camlar
    draw.polygon([(cx-w+10, cy-h), (cx-w+20, cy-h-15), (cx+w-20, cy-h-15), (cx+w-10, cy-h)], fill=(150, 200, 255))
    # Tekerlekler
    draw.ellipse([cx-w+5, cy+h-8, cx-w+20, cy+h+7], fill=(30, 30, 30))
    draw.ellipse([cx+w-20, cy+h-8, cx+w-5, cy+h+7], fill=(30, 30, 30))

    if label == 1:  # ── Hasarlı Araç ──────────────────────────
        # Göçük efekti (Düzensiz koyu renkli poligonlar)
        for _ in range(random.randint(1, 3)):
            dx = random.randint(cx-w+5, cx+w-15)
            dy = random.randint(cy-h+5, cy+h-5)
            draw.polygon([(dx, dy), (dx+8, dy-4), (dx+5, dy+6)], fill=(50, 50, 50))

        # Çizik efekti (Rastgele açılı ince çizgiler)
        for _ in range(random.randint(2, 5)):
            sx = random.randint(cx-w, cx+w-10)
            sy = random.randint(cy-h, cy+h)
            draw.line([(sx, sy), (sx+random.randint(5, 12), sy+random.randint(-10, 10))], fill=(255, 255, 255), width=1)

    # Gerçekçilik için rastgele Gaussian gürültü ekle
    arr = np.array(img, dtype=np.float32)
    arr += np.random.normal(0, 6, arr.shape)
    return np.clip(arr, 0, 255).astype(np.uint8)


def load_synthetic_data(n_per_class: int = 300):
    """Her sınıftan n_per_class adet görüntü üretir (CPU optimizasyonu için 300'e düşürüldü)."""
    X, y = [], []
    for label in [0, 1]:
        for _ in range(n_per_class):
            X.append(generate_synthetic_image(label, IMG_SIZE))
            y.append(label)
    # Karıştır (önce hepsi hasarsız, sonra hepsi hasarlı olmasın)
    combined = list(zip(X, y))
    random.shuffle(combined)
    X, y = zip(*combined)
    return np.array(X), np.array(y)


# ── Gerçek Veri Yükleyici ──────────────────────────────────────
def load_real_data(data_dir: str, img_size: int = 64):
    """
    Klasör yapısı beklenir:
        data/
          hasarsiz/   → *.jpg, *.jpeg, *.png
          hasarli/    → *.jpg, *.jpeg, *.png
    """
    X, y = [], []
    for label, cls in enumerate(CLASSES):
        folder = os.path.join(data_dir, cls)
        if not os.path.exists(folder):
            raise FileNotFoundError(
                f"Klasör bulunamadı: {folder}\n"
                f"Beklenen yapı: {data_dir}/hasarsiz/ ve {data_dir}/hasarli/"
            )
        files = [f for f in os.listdir(folder)
                 if f.lower().endswith(('.jpg', '.jpeg', '.png'))]
        print(f"  {cls}: {len(files)} dosya bulundu")
        for fname in files:
            img = cv2.imread(os.path.join(folder, fname))
            if img is None:
                continue  # Bozuk dosyaları atla
            img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)   # Renk kanalı düzelt
            img = cv2.resize(img, (img_size, img_size))  # Boyutu standartlaştır
            X.append(img)
            y.append(label)
    return np.array(X), np.array(y)


